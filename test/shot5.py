import asyncio
from playwright.async_api import async_playwright
async def center(pg, sel):
    b = await pg.locator(sel).first.bounding_box(); return b['x']+b['width']/2, b['y']+b['height']/2
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        pg = await b.new_page(viewport={'width':1280,'height':720})
        errs=[]
        pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('file:///home/claude/lootnight/dist/index.html')
        await pg.wait_for_timeout(300)
        await pg.click('[data-act=newGame]', force=True); await pg.evaluate("()=>{window.__lootnight.S.g.howto=false}")
        await pg.click('[data-act=gate]', force=True)
        await pg.keyboard.press('F1')
        await pg.click('[data-act=dbgMom]', force=True)
        await pg.keyboard.press('F1')
        await pg.wait_for_timeout(1200)
        await pg.click('[data-act=openPhone]', force=True)
        await pg.wait_for_timeout(300)
        await pg.screenshot(path='test/p1_ring.png')
        x,y = await center(pg, '[data-drag=answer]')
        await pg.mouse.move(x,y); await pg.mouse.down(); await pg.mouse.move(x+80,y,steps=5)
        await pg.screenshot(path='test/p1b_sliding.png')
        await pg.mouse.move(x+170,y,steps=5); await pg.mouse.up()
        await pg.wait_for_timeout(300)
        await pg.screenshot(path='test/p2_call.png')
        await pg.click('[data-act=closeGame]', force=True)
        await pg.keyboard.press('F1')
        await pg.click('[data-act=dbgBoss]', force=True)
        await pg.keyboard.press('F1')
        await pg.wait_for_timeout(500)
        await pg.click('[data-act=openPhone]', force=True)
        await pg.wait_for_timeout(200)
        x,y = await center(pg, '[data-hold=unlock]')
        await pg.mouse.move(x,y); await pg.mouse.down(); await pg.wait_for_timeout(600)
        await pg.screenshot(path='test/p3_unlock.png')
        await pg.wait_for_timeout(900); await pg.mouse.up()
        await pg.wait_for_timeout(200)
        await pg.screenshot(path='test/p4_chat.png')
        # answer boss rows by reading
        for _ in range(2):
            txt = await pg.locator('.ph-bubble b').inner_text()
            a,bb = [int(v) for v in txt.replace('= ?','').split('+')]
            await pg.click(f'[data-act=boss][data-arg="{a+bb}"]', force=True)
            await pg.wait_for_timeout(150)
        await pg.wait_for_timeout(300)
        # Monster
        await pg.click('[data-act=openMonster]', force=True)
        await pg.wait_for_timeout(200)
        await pg.screenshot(path='test/m1_grab.png')
        x,y = await center(pg, '[data-drag=lift]')
        await pg.mouse.move(x,y); await pg.mouse.down(); await pg.mouse.move(x,y-130,steps=6); await pg.mouse.up()
        await pg.wait_for_timeout(150)
        for _ in range(3):
            await pg.click('[data-act=monsterTab]', force=True); await pg.wait_for_timeout(80)
        x,y = await center(pg, '[data-drag=pull]')
        await pg.mouse.move(x,y); await pg.mouse.down(); await pg.mouse.move(x,y-40,steps=10)
        await pg.screenshot(path='test/m2_pull.png')
        await pg.mouse.move(x,y-90,steps=10); await pg.mouse.up()
        await pg.wait_for_timeout(150)
        x,y = await center(pg, '[data-hold=drink]')
        await pg.mouse.move(x,y); await pg.mouse.down(); await pg.wait_for_timeout(1200)
        await pg.screenshot(path='test/m3_drink.png')
        await pg.wait_for_timeout(1500); await pg.mouse.up()
        await pg.wait_for_timeout(150)
        x,y = await center(pg, '[data-drag=down]')
        await pg.mouse.move(x,y); await pg.mouse.down(); await pg.mouse.move(x,y+130,steps=6); await pg.mouse.up()
        await pg.wait_for_timeout(300)
        await pg.screenshot(path='test/m4_done.png')
        # microsleep
        await pg.keyboard.press('F1')
        for _ in range(3): await pg.click('[data-act=dbgDebt]', force=True)
        await pg.keyboard.press('F1')
        print('ERRORS', errs)
        await b.close()
asyncio.run(main())
