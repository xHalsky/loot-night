import asyncio, sys
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox','--autoplay-policy=no-user-gesture-required'])
        pg = await b.new_page(viewport={'width':1280,'height':720})
        errs=[]
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append('console:'+m.text) if m.type=='error' else None)
        await pg.goto('file:///home/claude/loot-night/dist/index.html')
        await pg.wait_for_timeout(800)
        await pg.screenshot(path='test/s0_title.png')
        await pg.click('[data-act=newGame]', force=True); await pg.evaluate("()=>{window.__lootnight.S.g.howto=false}")
        await pg.wait_for_timeout(500)
        await pg.screenshot(path='test/s1_town.png')
        await pg.click('[data-act=gate]', force=True)
        await pg.wait_for_timeout(9000)
        await pg.screenshot(path='test/s2_battle.png')
        await pg.keyboard.press('F1')
        await pg.click('[data-act=dbgMom]', force=True)
        await pg.wait_for_timeout(300)
        await pg.click('[data-act=openInt][data-arg=mom]', force=True)
        await pg.wait_for_timeout(500)
        await pg.screenshot(path='test/s3_mom.png')
        await pg.click('[data-act=closeGame]', force=True)
        await pg.click('[data-act=dbgVisit]', force=True)
        await pg.wait_for_timeout(3000)
        await pg.keyboard.press('Tab')
        await pg.wait_for_timeout(600)
        await pg.screenshot(path='test/s4_excel_visit.png')
        await pg.wait_for_timeout(2500)
        await pg.screenshot(path='test/s5_in.png')
        await pg.keyboard.press('Tab')
        await pg.click('[data-act=dbgEpic]', force=True)
        await pg.wait_for_timeout(1200)
        await pg.click('.bslot >> nth=0', force=True)
        await pg.wait_for_timeout(300)
        await pg.screenshot(path='test/s6_detail.png')
        print('ERRORS', errs)
        await b.close()
asyncio.run(main())
