// hourglass: the auto-pick mark (5x7); sand drains from top to bottom as away time adds up
function hourglass(x, y, f, idx = P.u6, sand = P.pale) {
  rectI(x, y, 5, 1, idx); rectI(x, y + 6, 5, 1, idx);
  putI(x, y + 1, idx); putI(x + 4, y + 1, idx); putI(x + 1, y + 2, idx); putI(x + 3, y + 2, idx);
  putI(x + 1, y + 4, idx); putI(x + 3, y + 4, idx); putI(x, y + 5, idx); putI(x + 4, y + 5, idx);
  const top = f < 0.34 ? 2 : f < 0.67 ? 1 : 0, bot = f < 0.34 ? 0 : f < 0.67 ? 1 : 2;
  if (top >= 1) { putI(x + 1, y + 1, sand); putI(x + 2, y + 1, sand); putI(x + 3, y + 1, sand); }
  if (top >= 2) putI(x + 2, y + 2, sand);
  if (f < 1) putI(x + 2, y + 3, sand);
  if (bot >= 1) { putI(x + 1, y + 5, sand); putI(x + 2, y + 5, sand); putI(x + 3, y + 5, sand); }
  if (bot >= 2) putI(x + 2, y + 4, sand);
}
